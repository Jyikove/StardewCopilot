    # **Stardew Copilot 使用帮助**

    Stardew Copilot 是您的星露谷小助手。当前版本适用于 macOS、Stardew Valley 1.6.15 和 SMAPI 4.5.2。

    #### **打开和关闭小助手**

    进入游戏存档后，您可以点击游戏右下角能量条上方的对话按钮，打开小助手。在 Enter 键未被其他功能占用的兼容场景中，也可以按 Enter 打开小助手；联机模式下默认使用 G 键。

    首次打开小助手时，需要在弹出的 API Key 配置窗口中输入您的 DeepSeek API Key。配置完成后，Key 会加密保存在 Mod 文件夹内。您可以使用 `/resetkey` [特殊指令](#特殊指令)重新配置 Key。

    单人模式下，打开小助手会暂停游戏时间，无需担心对话耽误游戏内的日程。但在联机模式下世界仍会继续运行。您可以点击右上角的“×”，或按 Esc 关闭小助手。关闭窗口不会打断正在生成的回答，您可以稍后重新打开窗口查看。

    #### **关于对话**

    您可以用自然的方式与小助手交流，提出与游戏相关的问题。小助手会按需读取您的游戏状态和进度，包括日期、时间、天气、运气、生命、体力、金钱、背包物品、农场作物、NPC 位置与好感度等信息。它也可以查看已加载的 Mod 清单，并按需查询可读取的配置和相关文档，帮助您了解 Mod 的用法。

    对于无法直接查询的内容，例如商店当前售卖的商品，您可以先打开对应的游戏界面，再使用 `/screen 您的问题` [特殊指令](#特殊指令)提问。小助手会分析当前游戏画面，并结合即时状态回答。由于它不一定能准确识别所有物品图标，建议在画面中显示物品名称、说明等文字后使用该指令。

    如果您认为回答不够详细、准确或及时，可以使用 `/search 您的问题` [特殊指令](#特殊指令)。小助手会深入查询即时游戏状态并联网检索，因此通常需要更长的响应时间。

    小助手会保留您与它的对话历史。同一存档、同一角色会沿用自己的对话，重新进入游戏后可以继续追问。您可以使用 `/clearchat` [特殊指令](#特殊指令)清除当前角色在该存档中的全部对话历史，并开始新对话。

    #### **关于待办**

    您可以在待办页面中记录想做的事，完成后勾选方框，将其标记为已完成；再次点击方框即可恢复为未完成。

    您也可以要求小助手添加待办，例如：“提醒我今天为作物浇水。”小助手会智能添加相应待办。

    小助手回答问题时，可以按需查看您的待办列表及完成状态，提供更合适的建议。您可以使用 `/cleartodo` [特殊指令](#特殊指令)清除当前角色在该存档中的全部待办。

    #### **特殊指令**

    您可以在对话输入框中输入以 `/` 开头的特殊指令，完成特定操作。在空输入框中键入 `/` 后，输入框上方会显示指令列表。使用上下方向键选择，再按 Enter 补全指令；补全不会立即执行，继续填写问题后再按 Enter 发送即可。

    特殊指令包括：

    `/clearchat` — 清除当前角色在该存档中的全部历史对话。
    `/cleartodo` — 清除当前角色在该存档中的全部待办。
    `/resetkey` — 重新配置 API Key。
    `/screen 您的问题` — 分析当前游戏画面。例如：“`/screen 商店里这些商品有没有值得购买的？`”
    `/search 您的问题` — 深入查询即时状态并检索。例如：“`/search 为我规划一下今年的夏季`”
    `/help 您的问题` — 询问小助手的相关问题。例如：“`/help 对话记录保存在哪里？`”
    """;
